package dev.vapor.transform.impl;

import dev.vapor.util.Insns;
import org.objectweb.asm.Opcodes;
import org.objectweb.asm.tree.InsnList;
import org.objectweb.asm.tree.InsnNode;
import org.objectweb.asm.tree.JumpInsnNode;
import org.objectweb.asm.tree.LabelNode;
import org.objectweb.asm.tree.VarInsnNode;

/**
 * Opaque predicate building blocks: instruction sequences whose outcome is the
 * same for <em>every</em> {@code int} value (overflow included), so the guarded
 * branch is decidable at runtime but not trivially at decompile time.
 *
 * <p>Every form is an arithmetic identity modulo 2³² (e.g.
 * {@code (v << 1) - v - v == 0}, {@code v * (v + 1)} is always even,
 * {@code v ^ (v >> 31) >= 0}). All facts are verified by <em>executing</em> the
 * generated bytecode over edge values and random inputs — see
 * {@code OpaquePredicatesTest}.</p>
 *
 * <p>Each {@code jump*} form consumes nothing and leaves nothing on the stack;
 * the branch itself is the only effect. {@code pushZero} leaves a literal 0.</p>
 */
public final class OpaquePredicates {

    /** Number of never-taken branch forms. */
    public static final int FALSE_FORMS = 6;
    /** Number of always-taken branch forms. */
    public static final int TRUE_FORMS = 3;
    /** Number of "push literal 0" forms. */
    public static final int ZERO_FORMS = 4;

    private OpaquePredicates() {
    }

    /** Appends {@code if (<always false>) goto target;} — the jump is never taken. */
    public static void jumpFalse(InsnList out, int slot, int form, LabelNode target) {
        switch (Math.floorMod(form, FALSE_FORMS)) {
            case 0 -> { // (v << 1) - v - v == 0 ; IFNE never taken
                out.add(load(slot));
                out.add(new InsnNode(Opcodes.ICONST_1));
                out.add(new InsnNode(Opcodes.ISHL));
                out.add(load(slot));
                out.add(new InsnNode(Opcodes.ISUB));
                out.add(load(slot));
                out.add(new InsnNode(Opcodes.ISUB));
                out.add(new JumpInsnNode(Opcodes.IFNE, target));
            }
            case 1 -> { // v * 3 - (v << 1) - v == 0
                out.add(load(slot));
                out.add(new InsnNode(Opcodes.ICONST_3));
                out.add(new InsnNode(Opcodes.IMUL));
                out.add(load(slot));
                out.add(new InsnNode(Opcodes.ICONST_1));
                out.add(new InsnNode(Opcodes.ISHL));
                out.add(new InsnNode(Opcodes.ISUB));
                out.add(load(slot));
                out.add(new InsnNode(Opcodes.ISUB));
                out.add(new JumpInsnNode(Opcodes.IFNE, target));
            }
            case 2 -> { // (v >> 1) * 2 + (v & 1) - v == 0
                out.add(load(slot));
                out.add(new InsnNode(Opcodes.ICONST_1));
                out.add(new InsnNode(Opcodes.ISHR));
                out.add(new InsnNode(Opcodes.ICONST_2));
                out.add(new InsnNode(Opcodes.IMUL));
                out.add(load(slot));
                out.add(new InsnNode(Opcodes.ICONST_1));
                out.add(new InsnNode(Opcodes.IAND));
                out.add(new InsnNode(Opcodes.IADD));
                out.add(load(slot));
                out.add(new InsnNode(Opcodes.ISUB));
                out.add(new JumpInsnNode(Opcodes.IFNE, target));
            }
            case 3 -> { // v ^ (v >> 31) >= 0 ; IFLT never taken
                out.add(load(slot));
                out.add(load(slot));
                Insns.pushInt(out, 31);
                out.add(new InsnNode(Opcodes.ISHR));
                out.add(new InsnNode(Opcodes.IXOR));
                out.add(new JumpInsnNode(Opcodes.IFLT, target));
            }
            case 4 -> { // (v - 1) | v is never 0 ; IFEQ never taken
                out.add(load(slot));
                out.add(new InsnNode(Opcodes.ICONST_1));
                out.add(new InsnNode(Opcodes.ISUB));
                out.add(load(slot));
                out.add(new InsnNode(Opcodes.IOR));
                out.add(new JumpInsnNode(Opcodes.IFEQ, target));
            }
            default -> { // v * (v + 1) is always even ; (… & 1) != 0 never happens
                out.add(load(slot));
                out.add(load(slot));
                out.add(new InsnNode(Opcodes.ICONST_1));
                out.add(new InsnNode(Opcodes.IADD));
                out.add(new InsnNode(Opcodes.IMUL));
                out.add(new InsnNode(Opcodes.ICONST_1));
                out.add(new InsnNode(Opcodes.IAND));
                out.add(new JumpInsnNode(Opcodes.IFNE, target));
            }
        }
    }

    /** Appends {@code if (<always true>) goto target;} — the jump is always taken. */
    public static void jumpTrue(InsnList out, int slot, int form, LabelNode target) {
        switch (Math.floorMod(form, TRUE_FORMS)) {
            case 0 -> { // v ^ (v >> 31) >= 0
                out.add(load(slot));
                out.add(load(slot));
                Insns.pushInt(out, 31);
                out.add(new InsnNode(Opcodes.ISHR));
                out.add(new InsnNode(Opcodes.IXOR));
                out.add(new JumpInsnNode(Opcodes.IFGE, target));
            }
            case 1 -> { // (v - 1) | v is never 0
                out.add(load(slot));
                out.add(new InsnNode(Opcodes.ICONST_1));
                out.add(new InsnNode(Opcodes.ISUB));
                out.add(load(slot));
                out.add(new InsnNode(Opcodes.IOR));
                out.add(new JumpInsnNode(Opcodes.IFNE, target));
            }
            default -> { // v * (v + 1) is always even
                out.add(load(slot));
                out.add(load(slot));
                out.add(new InsnNode(Opcodes.ICONST_1));
                out.add(new InsnNode(Opcodes.IADD));
                out.add(new InsnNode(Opcodes.IMUL));
                out.add(new InsnNode(Opcodes.ICONST_1));
                out.add(new InsnNode(Opcodes.IAND));
                out.add(new JumpInsnNode(Opcodes.IFEQ, target));
            }
        }
    }

    /** Appends code leaving a literal {@code 0} on the stack (for condition perturbation). */
    public static void pushZero(InsnList out, int slot, int form) {
        switch (Math.floorMod(form, ZERO_FORMS)) {
            case 0 -> { // (v << 2) - v * 4
                out.add(load(slot));
                out.add(new InsnNode(Opcodes.ICONST_2));
                out.add(new InsnNode(Opcodes.ISHL));
                out.add(load(slot));
                out.add(new InsnNode(Opcodes.ICONST_4));
                out.add(new InsnNode(Opcodes.IMUL));
                out.add(new InsnNode(Opcodes.ISUB));
            }
            case 1 -> { // (v << 1) - v - v
                out.add(load(slot));
                out.add(new InsnNode(Opcodes.ICONST_1));
                out.add(new InsnNode(Opcodes.ISHL));
                out.add(load(slot));
                out.add(new InsnNode(Opcodes.ISUB));
                out.add(load(slot));
                out.add(new InsnNode(Opcodes.ISUB));
            }
            case 2 -> { // v * 3 - (v << 1) - v
                out.add(load(slot));
                out.add(new InsnNode(Opcodes.ICONST_3));
                out.add(new InsnNode(Opcodes.IMUL));
                out.add(load(slot));
                out.add(new InsnNode(Opcodes.ICONST_1));
                out.add(new InsnNode(Opcodes.ISHL));
                out.add(new InsnNode(Opcodes.ISUB));
                out.add(load(slot));
                out.add(new InsnNode(Opcodes.ISUB));
            }
            default -> { // (v >> 1) * 2 + (v & 1) - v
                out.add(load(slot));
                out.add(new InsnNode(Opcodes.ICONST_1));
                out.add(new InsnNode(Opcodes.ISHR));
                out.add(new InsnNode(Opcodes.ICONST_2));
                out.add(new InsnNode(Opcodes.IMUL));
                out.add(load(slot));
                out.add(new InsnNode(Opcodes.ICONST_1));
                out.add(new InsnNode(Opcodes.IAND));
                out.add(new InsnNode(Opcodes.IADD));
                out.add(load(slot));
                out.add(new InsnNode(Opcodes.ISUB));
            }
        }
    }

    private static VarInsnNode load(int slot) {
        return new VarInsnNode(Opcodes.ILOAD, slot);
    }
}
